<?php
/** Proof — messages (spec "Proof", 2): post and the poll, earlier, the unread line, edit, delete, threads, reactions, pins, saved, scheduled, attachments. */
require __DIR__ . '/lib.php';
$w = channel_world();
$marco = as_member(27); $priya = as_member(26); $dana = as_member(30); $bea = as_member(28); $ann = as_member(29);
$launch = $w['launch'];

echo "1. Post and the poll\n";
$since = last_activity_id();
[$c, $b] = post($priya, $launch, 'Hello **launch** team');
$m1 = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $m1 > 0 && ($b['did'] ?? '') === 'Posted in #smoke-launch' && str_contains((string) $b['html'], 'id="message-row-' . $m1 . '"') && str_contains((string) $b['html'], '<strong>launch</strong>') && ($b['refresh'] ?? '') === 'messageChanged', 'message_post: the rendered row comes back');
$log = activity('message.post', $since);
$after = json_decode((string) $log[0]['after'], true);
ok(count($log) === 1 && (int) $log[0]['channel_id'] === $launch && (int) $log[0]['message_id'] === $m1 && $after['length'] === 17 && $after['has_attachments'] === false && !str_contains((string) $log[0]['after'], 'Hello'), 'message.post logged with the facts, never the words');
ok((int) one('SELECT last_read_message_id FROM channel_members WHERE channel_id = :c AND member_id = 26', ['c' => $launch]) === $m1, 'the author\'s cursor moved to it');
$r = req('GET', '/channels/' . $launch . '/since?after=' . ($m1 - 1), ['jar' => $marco]);
ok($r['code'] === 200 && str_contains($r['body'], 'id="message-row-' . $m1 . '"') && str_contains($r['headers'], 'X-Message-Hashes') && str_contains($r['headers'], 'HX-Trigger: {"readMoved":' . $m1 . '}'), 'the poll after the previous id answers the new row with HX-Trigger readMoved');
$r = req('GET', '/channels/' . $launch . '/since?after=' . $m1, ['jar' => $marco]);
ok($r['code'] === 204 && trim($r['body']) === '', 'the poll with nothing new: 204');
$r = req('GET', '/channels/' . $launch . '/since?after=' . $m1, ['jar' => $bea]);
ok($r['code'] === 404, 'Bea\'s poll: 404');
[$c, $d] = screen($dana, '/channels/' . $launch . '/since?after=0');
ok($c === 200 && count($d['new']) >= 1 && is_array($d['hashes']), 'as JSON: new rows and hashes');

echo "2. Load earlier and the unread line\n";
for ($i = 1; $i <= 60; $i++) { post($priya, $launch, 'line ' . $i); }
$r = page($marco, '/channels/' . $launch);
preg_match_all('/id="message-row-(\d+)"/', $r['body'], $mm);
$shown = array_map('intval', $mm[1]);
ok(count($shown) === 50 && $shown === array_values(array_unique($shown)) && min($shown) > $m1 && str_contains($r['body'], 'id="load-earlier-btn"') && str_contains($r['body'], 'id="unread-line"'), 'Marco opens on the last 50 with Load earlier; the unread line sits above the first unread');
ok(preg_match('/id="unread-line".*?id="message-row-(\d+)"/s', $r['body'], $u) === 1 && (int) $u[1] === min($shown), 'the line is right above the first unread of the page');
$r2 = page($marco, '/channels/' . $launch . '?before=' . min($shown));
preg_match_all('/id="message-row-(\d+)"/', $r2['body'], $mm2);
ok(count($mm2[1]) === 11 && max(array_map('intval', $mm2[1])) < min($shown), '?before= pages back: the 11 earlier ones');
[$c, $b] = act($marco, '/channels/read.php', ['channel' => $launch]);
$lastId = max($shown);
ok($c === 200 && (int) one('SELECT last_read_message_id FROM channel_members WHERE channel_id = :c AND member_id = 27', ['c' => $launch]) === $lastId && ($b['unread'] ?? -1) === 0, 'channel_mark_read moves the cursor to the latest; unread 0');
ok(!str_contains(page($marco, '/channels/' . $launch)['body'], 'id="unread-line"'), 'no line once read');
ok(count(activity('channel.read', $since)) === 1, 'channel.read logged once (the cursor moved)');
[$c, $b] = act($marco, '/channels/read.php', ['channel' => $launch, 'message' => $m1]);
ok($c === 200 && (int) one('SELECT last_read_message_id FROM channel_members WHERE channel_id = :c AND member_id = 27', ['c' => $launch]) === $lastId, 'a cursor never moves back');

echo "3. Edit and delete\n";
[$c, $b] = act($priya, '/channels/messages/edit.php', ['message' => $m1, 'markdown' => 'Hello launch team, edited']);
ok($c === 200 && message_db($m1)['edited_at'] !== null && message_db($m1)['plain_text'] === 'Hello launch team, edited' && str_contains((string) $b['html'], 'edited'), 'the author edits: the mark');
[$c, $b] = act($marco, '/channels/messages/edit.php', ['message' => $m1, 'markdown' => 'x']);
ok($c === 403 && msg($b) === 'Only the author edits a message.', 'another\'s edit refused');
[$c, $b] = post($dana, $launch, 'to be deleted');
$d1 = (int) $b['record_id'];
[$c, $b] = reply($marco, $d1, 'a reply under it');
$r1 = (int) $b['record_id'];
[$c, $b] = act($dana, '/channels/messages/delete-own.php', ['message' => $d1]);
ok($c === 200 && message_db($d1)['deleted_at'] !== null && message_db($d1)['plain_text'] === '' && message_db($r1)['thread_root_id'] == $d1 && str_contains((string) $b['html'], 'This message was deleted'), 'delete own: a tombstone; the reply keeps its thread');
[$c, $b] = act($dana, '/channels/messages/delete.php', ['message' => $r1]);
ok($c === 403, 'Dana cannot delete Marco\'s');
[$c, $b] = act($priya, '/channels/messages/delete-own.php', ['message' => $r1]);
ok($c === 403, 'nor Priya his through delete_own');
[$c, $b] = post($priya, $launch, 'Marco deletes this');
$d2 = (int) $b['record_id'];
[$c, $b] = act($marco, '/channels/messages/delete.php', ['message' => $d2]);
ok($c === 200 && message_db($d2)['deleted_at'] !== null, 'Marco (the owner) deletes Priya\'s');
$reg = json_decode(file_get_contents(dirname(__DIR__, 3) . '/mcp/action_registry.json'), true);
ok(($reg['actions']['message_delete']['approval'] ?? '') === 'deletion' && ($reg['actions']['channel_archive']['approval'] ?? '') === 'deletion' && ($reg['actions']['channel_announce']['approval'] ?? '') === 'other' && ($reg['actions']['channel_guest_add']['approval'] ?? '') === 'external_send', 'the registry: message_delete and channel_archive deletion, channel_announce other, channel_guest_add external_send');
$r = req('GET', '/channels/' . $launch . '/since?after=' . $d2 . '&hashes=' . urlencode(json_encode([(string) $d2 => 'stale'])), ['jar' => $marco]);
ok($r['code'] === 200 && str_contains($r['body'], 'id="message-row-' . $d2 . '" ') && str_contains($r['body'], 'hx-swap-oob="outerHTML"'), 'a changed row (its hash differs) comes back as an out-of-band swap');

echo "4. Threads\n";
[$c, $b] = post($priya, $launch, 'A question for the thread');
$root = (int) $b['record_id'];
[$c, $b] = reply($marco, $root, 'First answer');
$a1 = (int) $b['record_id'];
ok($c === 200 && message_db($a1)['thread_root_id'] == $root && (int) message_db($root)['reply_count'] === 1 && ($b['thread_root_id'] ?? 0) === $root, 'a reply lands in the thread; reply_count 1');
[$c, $b] = reply($dana, $a1, 'Reply to the reply');
ok($c === 200 && message_db((int) $b['record_id'])['thread_root_id'] == $root, 'replying to a reply joins the thread (the root)');
$bad = (int) one("INSERT INTO messages (channel_id, thread_root_id, author_member_id, body) VALUES (:c, :r, 27, '[]') RETURNING id", ['c' => $launch, 'r' => $root]);
$r = q("SELECT 1");
try { pdo()->exec("SELECT set_config('app.member_id', '27', false)"); one('INSERT INTO messages (channel_id, thread_root_id, author_member_id, body) VALUES (' . $launch . ', ' . $a1 . ', 27, \'[]\') RETURNING id'); ok(false, 'a reply to a reply by SQL: refused'); } catch (PDOException $e) { ok(str_contains($e->getMessage(), 'one level deep'), 'a reply to a reply by SQL: the database refuses in words'); }
[$c, $b] = reply($priya, $root, 'Also to the channel', ['also_to_channel' => 'yes']);
$also = (int) $b['record_id'];
ok($c === 200 && message_db($also)['also_to_channel'] === true, 'also_to_channel set');
$r = page($marco, '/channels/' . $launch);
ok(str_contains($r['body'], 'id="message-row-' . $also . '"') && !str_contains($r['body'], 'id="message-row-' . $a1 . '"'), 'the channel shows the also-sent reply, not the other');
$r = page($marco, '/channels/' . $launch . '/threads/' . $root);
ok($r['code'] === 200 && str_contains($r['body'], 'id="thread-pane"') && str_contains($r['body'], 'id="thread-row-' . $root . '"') && str_contains($r['body'], 'id="thread-row-' . $a1 . '"') && str_contains($r['body'], 'id="thread-composer"'), 'the thread page: the root, the replies, the composer');
$r = req('GET', '/channels/' . $launch . '/threads/' . $root, ['jar' => $marco, 'headers' => ['HX-Request: true', 'HX-Target: right-pane-body']]);
ok($r['code'] === 200 && str_contains($r['headers'], 'X-Pane-Title: Thread in #smoke-launch') && !str_contains($r['body'], 'page-header'), 'asked for the right pane: the fragment with its title');
$r = req('GET', '/channels/' . $launch . '/threads/' . $root . '/since?after=' . $root, ['jar' => $dana]);
ok($r['code'] === 200 && str_contains($r['body'], 'id="thread-row-' . $a1 . '"'), 'the thread\'s poll');
ok(page($bea, '/channels/' . $launch . '/threads/' . $root)['code'] === 404, 'Bea: 404');
[$c, $d] = screen($marco, '/channels/' . $launch . '/threads/' . $root);
ok($c === 200 && ($d['root_id'] ?? 0) === $root && count($d['messages']) >= 4, 'the thread as JSON');

echo "5. Reactions, pins, saved\n";
[$c, $b] = act($dana, '/channels/messages/react.php', ['message' => $root, 'emoji' => '👍']);
ok($c === 200 && str_contains((string) $b['html'], 'sp-reaction active') && str_contains((string) $b['html'], '👍'), 'a reaction toggles on (mine marked)');
[$c, $b] = act($marco, '/channels/messages/react.php', ['message' => $root, 'emoji' => ':thumbsup:']);
ok($c === 200 || $c === 422, 'a :shortcode: is looked up (' . $c . ')');
[$c, $b] = act($priya, '/channels/messages/react.php', ['message' => $root, 'emoji' => '👍']);
ok((int) one('SELECT count(*) FROM message_reactions WHERE message_id = :m AND emoji = :e', ['m' => $root, 'e' => '👍']) === 2, 'two 👍');
[$c, $b] = act($dana, '/channels/messages/unreact.php', ['message' => $root, 'emoji' => '👍']);
ok($c === 200 && (int) one('SELECT count(*) FROM message_reactions WHERE message_id = :m AND emoji = :e', ['m' => $root, 'e' => '👍']) === 1, 'and off');
[$c, $b] = act($bea, '/channels/messages/react.php', ['message' => $root, 'emoji' => '👍']);
ok($c === 404, 'a non-member: 404');
[$c, $b] = act($dana, '/channels/messages/react.php', ['message' => $root, 'emoji' => 'abc']);
ok($c === 422, 'letters are not an emoji: 422');
[$c, $b] = act($dana, '/channels/pins/add.php', ['channel' => $launch, 'message' => $root]);
ok($c === 200 && (bool) one('SELECT EXISTS (SELECT 1 FROM channel_pins WHERE channel_id = :c AND message_id = :m)', ['c' => $launch, 'm' => $root]), 'pinned');
[$c, $b] = act($dana, '/channels/pins/add.php', ['channel' => $launch, 'message' => $root]);
ok($c === 422 && msg($b) === 'That is pinned already.', 'twice: the sentence');
[$c, $b] = act($dana, '/channels/pins/add.php', ['channel' => $launch, 'page' => $w['runbook']]);
ok($c === 200, 'a page pinned');
[$c, $b] = act($dana, '/channels/bookmarks/save.php', ['channel' => $launch, 'title' => 'Our site', 'url' => 'https://example.com', 'emoji' => '🌐']);
$bk = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $bk > 0, 'a bookmark saved');
[$c, $b] = act($dana, '/channels/bookmarks/save.php', ['channel' => $launch, 'title' => 'Both', 'url' => 'https://example.com', 'page' => $w['runbook']]);
ok($c === 422 && isset(fields($b)['url']), 'a link and a page at once: 422');
$r = page($marco, '/channels/' . $launch . '/pins');
ok($r['code'] === 200 && str_contains($r['body'], 'id="bookmark-' . $bk . '"') && str_contains($r['body'], 'A question for the thread') && str_contains($r['body'], 'SMOKE Runbook'), 'the pins screen lists both pins and the bookmark');
[$c, $b] = act($marco, '/channels/pins/remove.php', ['channel' => $launch, 'page' => $w['runbook']]);
ok($c === 200, 'unpinned the page');
[$c, $b] = act($marco, '/channels/bookmarks/delete.php', ['bookmark' => $bk]);
ok($c === 200 && one('SELECT count(*) FROM channel_bookmarks WHERE id = :b', ['b' => $bk]) == 0, 'the bookmark deleted');
[$c, $b] = act($dana, '/channels/messages/save.php', ['message' => $root]);
ok($c === 200 && (bool) one('SELECT EXISTS (SELECT 1 FROM saved_messages WHERE member_id = 30 AND message_id = :m)', ['m' => $root]), 'saved for later');
$r = page($dana, '/saved');
ok($r['code'] === 200 && str_contains($r['body'], 'id="saved-row-' . $root . '"'), 'it shows on Saved');
[$c, $b] = act($dana, '/channels/messages/save.php', ['message' => $root, 'saved' => 'no']);
ok($c === 200 && !str_contains(page($dana, '/saved')['body'], 'id="saved-row-' . $root . '"'), 'and goes');

echo "6. Scheduled\n";
$t = (new DateTimeImmutable('+1 hour'))->format('Y-m-d H:i');
[$c, $b] = post($priya, $launch, 'later words', ['schedule_for' => $t]);
$s1 = (int) ($b['record_id'] ?? 0);
ok($c === 200 && $s1 > 0 && message_db($s1)['sent_at'] === null && message_db($s1)['scheduled_for'] !== null && str_starts_with((string) $b['did'], 'Scheduled for'), 'a scheduled message: unsent');
ok(!str_contains(page($marco, '/channels/' . $launch)['body'], 'id="message-row-' . $s1 . '"'), 'unseen by others');
$r = page($priya, '/channels/scheduled');
ok($r['code'] === 200 && str_contains($r['body'], 'id="scheduled-' . $s1 . '"') && str_contains($r['body'], 'later words'), 'shown to its author with its time');
[$c, $b] = post($priya, $launch, 'yesterday', ['schedule_for' => '2020-01-01 10:00']);
ok($c === 422 && isset(fields($b)['schedule_for']), 'a past time: 422');
[$c, $b] = act($marco, '/channels/messages/schedule.php', ['message' => $s1, 'schedule_for' => $t]);
ok($c === 404 || $c === 403, 'another cannot touch it');
pdo()->exec("UPDATE messages SET scheduled_for = now() - interval '1 minute' WHERE id = $s1");
$n = (int) one('SELECT sp_pass_scheduled()');
ok($n >= 1 && message_db($s1)['sent_at'] !== null && str_contains(page($marco, '/channels/' . $launch)['body'], 'id="message-row-' . $s1 . '"'), 'released by sp_pass_scheduled(): seen');
[$c, $b] = post($priya, $launch, 'to cancel', ['schedule_for' => $t]);
$s2 = (int) $b['record_id'];
[$c, $b] = act($priya, '/channels/messages/unschedule.php', ['message' => $s2]);
ok($c === 200 && message_db($s2) === [], 'unschedule discards it');
[$c, $b] = post($priya, $launch, 'send now instead', ['schedule_for' => $t]);
$s3 = (int) $b['record_id'];
[$c, $b] = act($priya, '/channels/messages/schedule.php', ['message' => $s3, 'schedule_for' => '']);
ok($c === 200 && message_db($s3)['sent_at'] !== null, 'schedule with an empty time sends now');

echo "7. Attachments\n";
[$c, $b] = upload($dana, '/files/upload.php', ['message' => $launch], proof_file('chan.png', png_bytes(20, 10)), 'chan.png', 'image/png');
$aid = (int) ($b['attachment']['attachment_id'] ?? 0);
ok($c === 200 && $aid > 0, 'a file uploaded against the channel (a pending slot)');
[$c, $b] = post($dana, $launch, 'with a picture', ['attachments' => (string) $aid]);
$mp = (int) $b['record_id'];
ok($c === 200 && (int) message_db($mp)['attachment_count'] === 1 && (int) one('SELECT record_id FROM attachments WHERE id = :a', ['a' => $aid]) === $mp && str_contains((string) $b['html'], '/files/' . $aid . '/thumb'), 'posted with it: the row points at the message, the thumbnail in the row');
ok(page($marco, '/files/' . $aid)['code'] === 200, 'served through /files/{id} to a member');
ok(page($bea, '/files/' . $aid)['code'] === 404, 'refused to a non-member');
[$c, $b] = upload($bea, '/files/upload.php', ['message' => $launch], proof_file('chan2.png', png_bytes()), 'chan2.png', 'image/png');
ok($c === 404, 'Bea cannot upload against it');
act($dana, '/channels/messages/delete-own.php', ['message' => $mp]);
ok(one('SELECT count(*) FROM attachments WHERE id = :a', ['a' => $aid]) == 0, 'deleting the message removes its file');
finish();
