<?php
/** The record picker's endpoint (html/pick/index.php, app/pickers.php): refusals, gates, search, escaping, paging, params, the membership walls. */
require __DIR__ . '/lib.php';
$w = picker_world();
$marco = as_member(27); $priya = as_member(26); $bea = as_member(28); $ann = as_member(29); $owner = as_member(1);
$elsewhere = (int) $w['elsewhere'];

echo "-- refusals answer a fragment, never a page\n";
[$c, $b, $r] = pick('', 'space');
ok($c === 401 && str_contains($b, 'Sign in again') && !str_contains($b, '<html') && $r['location'] === '', 'anonymous: 401 with a fragment, no redirect to the launcher');
[$c, $b] = pick($marco, 'nope');
ok($c === 404 && str_contains($b, 'That list does not exist.') && !str_contains($b, '<html'), 'an unknown source: 404 "That list does not exist."');
[$c, $b] = pick($marco, '');
ok($c === 404, 'no source: 404');
[$c, $b] = pick($marco, 'SPACE!!');
ok($c === 200 && count(rows_of($b)) > 0, 'a source key is cleaned to [a-z0-9_] (SPACE!! reads as space)');
$tok = run_token(40, 9001);
$r = req('GET', '/pick/?source=space', ['headers' => as_agent($tok)]);
ok($r['code'] === 403 && str_contains($r['body'], 'an agent uses the tools'), 'an agent (run token): 403, the picker is for people');
$r = req('POST', '/pick/', ['jar' => $marco, 'form' => ['source' => 'space']]);
ok($r['code'] === 405, 'a POST is refused (405): a search is a GET');
[$c, $b] = pick($ann, 'member', ['space' => $w['product']]);
ok($c === 403, 'a guest may not choose from the directory (member): 403');

echo "-- member: the gate follows the screen that uses the field\n";
[$c, $b] = pick($marco, 'member');
ok($c === 403 && str_contains($b, 'Say what the person is for'), 'member with no space and no page: 403');
[$c, $b] = pick($priya, 'member', ['space' => $w['product']]);
ok($c === 403 && str_contains($b, 'may not add people to that space'), 'member for a space: a plain member (Priya) is refused');
[$c, $b] = pick($bea, 'member', ['space' => $w['leads']]);
ok($c === 403, 'member for a private space Bea does not see: refused');
[$c, $b] = pick($marco, 'member', ['space' => $w['product'], 'q' => 'SMOKE']);
$names = labels_of($b);
ok($c === 200 && !in_array('SMOKE Marco', $names, true) && !in_array('SMOKE Priya', $names, true) && $names !== [], 'member for Product (its owner Marco asks): leaves out those already in (Marco, Priya), lists the rest: ' . implode(', ', array_slice($names, 0, 4)));
[$c, $b] = pick($marco, 'member', ['space' => $w['product'], 'q' => 'bea']);
ok(count(rows_of($b)) === 1 && str_contains(labels_of($b)[0], 'Bea'), 'search "bea" finds Bea alone (case-insensitive)');
$pick1 = (int) $w['leads'];                                        // Marco's private space: only he is in it
[$c, $b] = pick($marco, 'member', ['space' => $pick1, 'q' => 'SMOKE Seamus']);
ok(labels_of($b) === ['SMOKE Seamus (agent)'] && str_contains($b, '>Agent<'), 'an agent is listed as "(agent)" with a badge');
[$c, $b] = pick($marco, 'member', ['space' => $pick1, 'q' => 'SMOKE']);
$people = labels_of($b);
ok($people !== [] && !preg_grep('/\(agent\)/', array_slice($people, 0, 20)), 'people come before agents (the first 20 rows hold no agent)');
[$c, $b] = pick($priya, 'member', ['page' => $w['handbook']]);
ok($c === 403 && str_contains($b, 'may not share that page'), 'member for a page: Priya (not full on the handbook) is refused');
[$c, $b] = pick($marco, 'member', ['page' => $w['handbook']]);
ok($c === 200 && count(rows_of($b)) > 3, 'member for a page: Marco (full) sees the directory');
[$c, $b] = pick($marco, 'member', ['page' => 'not-a-uuid']);
ok($c === 403, 'a page param that is not a UUID is no page: 403');

echo "-- escaping, limits and the LIKE wildcards\n";
[$c, $b] = pick($marco, 'member', ['space' => $w['product'], 'q' => '<script>alert(1)</script>']);
ok($c === 200 && !str_contains($b, '<script>') && str_contains($b, 'No person matches') && str_contains($b, '&lt;script&gt;'), 'the empty state names the query with its words escaped');
[$c, $b] = pick($marco, 'member', ['space' => $w['product'], 'q' => '%']);
ok(rows_of($b) === [], 'q=% is a literal percent, not "everything"');
[$c, $b] = pick($marco, 'member', ['space' => $w['product'], 'q' => '_']);
ok(rows_of($b) === [], 'q=_ is a literal underscore');
[$c, $b] = pick($marco, 'member', ['space' => $w['product'], 'q' => str_repeat('a', 500)]);
ok($c === 200, 'a 500-character query is cut at 80 and answered');
[$c, $b] = pick($marco, 'member', ['space' => $w['product'], 'q' => "bea' OR '1'='1"]);
ok($c === 200 && rows_of($b) === [], 'a quote in the query is data');

echo "-- spaces: three lists, three rules\n";
[$c, $b] = pick($marco, 'space');
$visible = labels_of($b);
ok($c === 200 && count(values_of($b)) === 25, 'space: the live spaces the caller sees (first page)');
[$c, $b] = pick($bea, 'space', ['q' => 'SMOKE Product']);
ok(count(rows_of($b)) === 1, 'space: a closed space is listed to everyone (it is discoverable; its pages are not)');
[$c, $b] = pick($marco, 'space', ['q' => 'Design leads']);
ok(count(rows_of($b)) === 1, 'space: Marco sees his private space');
[$c, $b] = pick($bea, 'space', ['q' => 'Design leads']);
ok(rows_of($b) === [], 'space: a private space is never listed to someone outside it');
[$c, $b] = pick($marco, 'space_page', ['q' => 'SMOKE Product']);
ok($c === 200 && in_array('🚀 SMOKE Product', labels_of($b), true), 'space_page: where Marco may write pages (the icon leads the label)');
[$c, $b] = pick($priya, 'space_member', ['q' => 'Product']);
ok(count(rows_of($b)) === 1, 'space_member: Priya belongs to Product');
[$c, $b] = pick($bea, 'space_member', ['q' => 'Product']);
ok(rows_of($b) === [], 'space_member: Bea does not');
[$c, $b] = pick($bea, 'space_export');
ok($c === 403 && str_contains($b, 'may not export'), 'space_export: Bea has no export.space: 403');
[$c, $b] = pick($marco, 'space_export', ['q' => 'SMOKE Product']);
ok($c === 200 && count(rows_of($b)) === 1, 'space_export: Marco owns Product');
[$c, $b] = pick($owner, 'space_export', ['q' => 'SMOKE Product']);
ok($c === 200 && count(rows_of($b)) === 1, 'space_export: the Spaces admin sees every space');
[$c, $b] = pick($marco, 'space_import');
ok($c === 200 && count(rows_of($b)) > 0, 'space_import: the spaces Marco may import into');
[$c, $b] = pick($marco, 'channel_export', ['q' => 'smoke-launch']);
ok($c === 200 && count(rows_of($b)) === 1 && str_contains(labels_of($b)[0], '#smoke-launch'), 'channel_export: "#smoke-launch" with its space as the detail');
[$c, $b] = pick($bea, 'channel_export');
ok($c === 403, 'channel_export: Bea may not export a channel');

echo "-- paging: 25 a page, Show more, the last page\n";
[$c, $b] = pick($marco, 'space', ['q' => 'SMOKE Pick']);
ok(count(rows_of($b)) === 25 && str_contains($b, 'record-picker-more') && str_contains($b, 'of 31 shown') , 'space "SMOKE Pick": 25 rows and "Show more — 25 of 31 shown"');
ok(str_contains($b, 'id="record-picker-list"') && str_contains($b, 'page=2') && str_contains($b, 'source=space'), 'the Show more row asks for page 2 of the same source and query');
[$c, $b2] = pick($marco, 'space', ['q' => 'SMOKE Pick', 'page' => 2]);
ok(count(rows_of($b2)) === 6 && !str_contains($b2, 'record-picker-list') && !str_contains($b2, 'record-picker-more'), 'page 2: the last 6 rows only, no list wrapper, no more button');
ok(array_intersect(values_of($b), values_of($b2)) === [], 'page 2 repeats nothing of page 1');
[$c, $b3] = pick($marco, 'space', ['q' => 'SMOKE Pick', 'page' => 99]);
ok($c === 200 && count(rows_of($b3)) === 6, 'a page past the end answers the last page');
[$c, $b] = pick($marco, 'member', ['space' => $pick1, 'q' => 'SMOKE Person']);
ok(count(rows_of($b)) === 25 && str_contains($b, 'of 30 shown'), 'member "SMOKE Person": 25 rows of 30 (a SQL page, counted)');
[$c, $b] = pick($marco, 'member', ['space' => $pick1, 'q' => 'SMOKE Person', 'page' => 2]);
ok(count(rows_of($b)) === 5 && !str_contains($b, 'record-picker-more') && labels_of($b)[0] === 'SMOKE Person 26', 'member page 2: the last 5, in name order (Person 26 first)');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Bulk']);
ok(count(rows_of($b)) === 25 && str_contains($b, 'of 60 shown'), 'page "SMOKE Bulk": 25 rows of 60');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Bulk', 'page' => 3]);
ok(count(rows_of($b)) === 10, 'page 3 of 60 pages: the last 10');

echo "-- selected: the chosen row is marked\n";
[$c, $b] = pick($marco, 'space', ['q' => 'SMOKE Product', 'selected' => $w['product']]);
ok(str_contains($b, 'record-picker-row active') && str_contains($b, 'aria-selected="true"'), 'a space: the row of `selected` is active');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Pricing 2027', 'selected' => $w['pricing2027']]);
ok(str_contains($b, 'record-picker-row active'), 'a page (a UUID): the row of `selected` is active');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Pricing 2027', 'selected' => "x' OR 1=1"]);
ok($c === 200 && !str_contains($b, 'record-picker-row active'), 'a `selected` that is neither digits nor a UUID is ignored');

echo "-- pages: the space param, editable, pages_only, except, and the membership wall\n";
[$c, $b] = pick($marco, 'page', ['space' => $w['product'], 'q' => 'SMOKE Pricing']);
$t = labels_of($b);
ok(count($t) === 2 && in_array('SMOKE Pricing', $t, true) && in_array('SMOKE Pricing 2027', $t, true), 'page with space=Product: only that space\'s pages: ' . implode(' | ', $t));
[$c, $b] = pick($bea, 'page', ['space' => $w['product'], 'q' => 'SMOKE Pricing']);
ok($c === 200 && rows_of($b) === [], 'page with space=Product for Bea (not a member): nothing is listed');
[$c, $b] = pick($bea, 'page', ['q' => 'SMOKE Pricing']);
ok(rows_of($b) === [], 'page: Bea sees none of Product\'s pages');
[$c, $b] = pick($bea, 'page', ['q' => "SMOKE Bea"]);
ok(labels_of($b) === ["SMOKE Bea's notes"], 'page: Bea sees her own private page');
[$c, $b] = pick($marco, 'page', ['q' => "SMOKE Bea"]);
ok(rows_of($b) === [], 'page: Marco never sees Bea\'s private page');
[$c, $b] = pick($bea, 'page', ['q' => 'SMOKE Elsewhere']);
ok(labels_of($b) === ['SMOKE Elsewhere page'], 'page (not editable): an open space Bea does not belong to still shows the page she may read');
[$c, $b] = pick($bea, 'page', ['q' => 'SMOKE Elsewhere', 'editable' => 1]);
ok(rows_of($b) === [], 'page editable=1: a page of a space Bea does not belong to is never offered as a parent, though everyone may edit there');
[$c, $b] = pick($bea, 'page', ['space' => $elsewhere, 'q' => 'SMOKE Elsewhere']);
ok(rows_of($b) === [], 'page space=<an open space Bea is not in>: nothing');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Elsewhere', 'editable' => 1]);
ok(labels_of($b) === ['SMOKE Elsewhere page'], 'page editable=1: Marco belongs to that space (he made it)');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Tasks']);
ok(count(rows_of($b)) === 1 && str_contains($b, '>Database<'), 'page: a database is a page, badged Database');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Tasks', 'pages_only' => 1]);
ok(rows_of($b) === [], 'page pages_only=1: databases left out');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Fix the login']);
ok(rows_of($b) === [], 'page: a database row is not a page to pick');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Pricing', 'except' => $w['pricing']]);
ok(labels_of($b) === ['SMOKE Pricing 2027'], 'page except=<uuid>: the page being moved is left out');
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Pricing', 'except' => 'not-a-uuid']);
ok(count(rows_of($b)) === 2, 'an except that is not a UUID is ignored');

echo "-- the union of params: only the declared ones reach a source\n";
[$c, $b] = pick($marco, 'page', ['q' => 'SMOKE Pricing', 'channel' => 1, 'bogus' => 'x; DROP TABLE pages']);
ok($c === 200 && count(rows_of($b)) === 2, 'undeclared params (channel, bogus) are ignored');

echo "-- channels: add a member, add a guest\n";
$launch = $w['launch']; $leads = $w['leads_channel'];
[$c, $b] = pick($marco, 'channel_member', ['channel' => $launch, 'q' => 'SMOKE']);
$names = labels_of($b);
ok($c === 200 && !in_array('SMOKE Seamus (agent)', $names, true) && !in_array('SMOKE Priya', $names, true), 'channel_member: those already in #smoke-launch (Seamus, Priya, Marco) are not offered: ' . implode(', ', $names));
[$c, $b] = pick($marco, 'channel_member', ['channel' => $leads]);
ok($c === 200 && !in_array('SMOKE Priya', labels_of($b), true) && !in_array('SMOKE Marco', labels_of($b), true), 'channel_member for the private channel: Priya and Marco are in, so not offered');
[$c, $b] = pick($bea, 'channel_member', ['channel' => $leads]);
ok($c === 403, 'channel_member: Bea cannot see the private channel: 403');
[$c, $b] = pick($marco, 'channel_member', []);
ok($c === 403, 'channel_member with no channel: 403');
[$c, $b] = pick($marco, 'channel_guest', ['channel' => $launch]);
ok($c === 200 && rows_of($b) === [], 'channel_guest: Ann is already in #smoke-launch, so no guest is offered');
[$c, $b] = pick($priya, 'channel_guest', ['channel' => $launch]);
ok($c === 403, 'channel_guest: Priya is not the channel\'s owner: 403');
[$c, $b] = pick($marco, 'channel_guest', ['channel' => $leads]);
ok($c === 200 && labels_of($b) === [(string) one('SELECT display_name FROM members WHERE id = 29')], 'channel_guest for the private channel: Ann is offered');

echo "-- guests of a page\n";
[$c, $b] = pick($marco, 'guest', ['page' => $w['pricing']]);
ok($c === 200 && count(rows_of($b)) === 1, 'guest: Marco (full, share.guest) is offered the guest');
[$c, $b] = pick($priya, 'guest', ['page' => $w['pricing']]);
ok($c === 403 && str_contains($b, 'may not share to a guest'), 'guest: Priya has no share.guest: 403');
[$c, $b] = pick($marco, 'guest', []);
ok($c === 403, 'guest with no page: 403');

echo "-- databases\n";
[$c, $b] = pick($marco, 'database', ['q' => 'SMOKE']);
$d = labels_of($b);
ok($c === 200 && in_array('SMOKE Tasks', $d, true) && in_array('SMOKE Epics', $d, true), 'database: Tasks and Epics');
[$c, $b] = pick($bea, 'database', ['q' => 'SMOKE Tasks']);
ok(rows_of($b) === [], 'database: Bea sees no database of Product');
[$c, $b] = pick($marco, 'database', ['q' => 'SMOKE Tasks', 'editable' => 1]);
ok(count(rows_of($b)) === 1, 'database editable=1: the one Marco may write in');
finish();
